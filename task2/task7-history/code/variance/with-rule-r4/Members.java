package com.thinking.ticket;

import java.util.Optional;

/**
 * 회원 명부에게 기대하는 역할.
 *
 * <p>변경 축: 회원을 확인하는 일은 정책이 통제하지 않는 남의 것(사내 저장소)에 있고,
 * 저장소가 DB든 회원 서비스 호출이든 예매 정책은 그대로여야 한다. 그 방향을 뒤집으려고 둔다.
 *
 * <p>너비: 정책이 명부에 묻는 것은 하나다 — 그 회원을 데려와 달라. 이름도 그 밖의 무엇도 쓰지 않는다.
 * 등록됐는지만 묻던 자리가 넓어진 이유는, 이제 정책이 회원 자신에게 예매를 맡기기 때문이다.
 *
 * <p>명부에 없으면 비어 있는 값을 준다. 없는 회원을 어떻게 볼지는 명부가 아니라 예매 정책이 정한다.
 */
public interface Members {

    Optional<Member> byId(long userId);
}
