package com.thinking.ticket;

/**
 * 회원의 포인트를 관리하는 쪽에게 기대하는 역할.
 *
 * <p>변경 축: 포인트 잔액은 정책이 통제하지 않는 남의 것(사내 포인트 시스템)에 있다.
 * 그것이 사내 시스템이든 다른 무엇이든 예매 정책은 그대로여야 하므로 방향을 뒤집는다.
 *
 * <p>너비: 예매가 필요로 하는 것은 차감뿐이다. 잔액을 묻는 통로는 쓰는 곳이 없어 열지 않는다.
 *
 * <p>"잔액이 모자라면 안 된다"는 규칙은 잔액을 가진 쪽이 스스로 지킨다. 그래서 여기서는
 * 잔액을 물어보고 정책이 대신 비교하지 않고, 차감을 시도한 뒤 그쪽의 답을 받는다.
 */
public interface Points {

    /** 차감에 성공하면 true, 잔액이 모자라면 false. */
    boolean deduct(long userId, int amount);
}
