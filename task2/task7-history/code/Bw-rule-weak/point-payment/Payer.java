package com.thinking.ticket;

/**
 * 이번 예매의 값을 치르는 자.
 *
 * <p>변경 축: 결제 수단이 늘어난다. 카드 하나였던 것이 포인트로 늘었고, 그때 예매 절차는
 * 한 줄도 바뀌지 않았다. 창구가 수단을 알지 않도록 그 자리를 이 역할로 비워 둔다.
 *
 * <p>너비: 창구가 아는 것은 치를 금액뿐이다. 누가 무엇으로 치르는지는 이 객체가 이미 안다 —
 * 이번 요청 몫으로 만들어졌기 때문이다.
 *
 * <p>못 치렀을 때 그것이 어떤 실패인지는 수단마다 다르다(카드 거절과 포인트 부족은 다른 일이다).
 * 그 판단은 수단을 아는 쪽의 몫이라 여기서 예외로 나간다.
 */
public interface Payer {

    /** 그 금액을 치른다. 치르지 못하면 그 수단이 아는 실패로 거부한다. */
    void pay(int amount);
}
