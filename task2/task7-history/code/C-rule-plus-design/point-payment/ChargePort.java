package com.thinking.ticket;

/**
 * 대가를 청구하는 역할.
 *
 * <p>협력의 행위 {@code e(대가를 청구한다)}가 앉는 자리다. 무엇으로 청구하는지(카드·포인트)는 이 역할
 * 뒤에 숨는다 — {@link TicketService}는 "청구하라"고 시킬 뿐, 수단을 묻지 않는다.
 *
 * <p><b>누구에게 청구하는가는 이 메시지에 없다.</b> 결제 수단마다 필요한 정보가 다르기 때문이다
 * (카드는 카드정보, 포인트는 회원). 그 정보는 {@link PaymentMethods}가 담당자를 고를 때 미리 매어 두고,
 * 여기에는 수단과 무관한 <b>금액</b>만 남긴다. 덕분에 어떤 구현도 자기가 안 쓰는 파라미터를 받지 않는다.
 *
 * <p><b>계약(모든 구현이 지켜야 한다).</b> {@code amount}만큼 청구한다.
 * 성공하면 정상 반환한다. 실패하면 예매를 중단시키는 {@link RuntimeException}을 던진다 —
 * 실패의 이유는 수단마다 다르므로 예외 타입도 다르지만, <b>"실패면 던진다"는 약속은 같다.</b>
 * 부분적으로 청구된 채 반환하지 않는다.
 */
interface ChargePort {

    void charge(int amount);
}
